"""Deterministic normalization for model-provided subagent type names.

`subagent_type` is generated by an LLM, so mechanically equivalent spellings
must not fail an exact-match dispatcher. This module only normalizes
separators, case, whitespace and Unicode dash variants; it never performs
edit-distance or synonym matching.
"""

from __future__ import annotations

import re
from typing import Any, Collection

_UNICODE_DASH_TRANSLATION = str.maketrans(
    {
        "\u2010": "-",  # HYPHEN
        "\u2011": "-",  # NON-BREAKING HYPHEN
        "\u2012": "-",  # FIGURE DASH
        "\u2013": "-",  # EN DASH
        "\u2014": "-",  # EM DASH
        "\u2015": "-",  # HORIZONTAL BAR
        "\u2212": "-",  # MINUS SIGN
        "\uff0d": "-",  # FULLWIDTH HYPHEN-MINUS
        "\u00ad": "",   # SOFT HYPHEN (invisible)
        "\u00a0": " ",  # NO-BREAK SPACE
    }
)
_SEPARATORS_RE = re.compile(r"[\s_\-]+")


def normalize_subagent_type(value: object) -> str:
    """Normalize Unicode dashes and surrounding whitespace.

    The result keeps the original separator style (`-`, `_` or spaces), so an
    exact match still has a chance before canonical matching is attempted.
    """
    text = str(value or "")
    if not text:
        return ""
    return text.translate(_UNICODE_DASH_TRANSLATION).strip()


def canonical_subagent_key(value: object) -> str:
    """Return a separator- and case-insensitive key for a subagent name."""
    return _SEPARATORS_RE.sub("", normalize_subagent_type(value)).casefold()


def subagent_spec_name(spec: object) -> str:
    """Return the registered name from a SubAgentConfig or DeepAgent-like spec."""
    card = getattr(spec, "agent_card", None) or getattr(spec, "card", None)
    return str(getattr(card, "name", "") or "")


def resolve_subagent_type_name(
    parent_agent: Any,
    subagent_type: object,
    allowed_subagent_types: Collection[str] | None = None,
) -> str:
    """Resolve a model-provided type to a registered name when possible.

    The resolver uses the parent agent's tolerant lookup first, then falls
    back to a unique canonical match inside ``allowed_subagent_types``. When no
    unique match exists, it returns the normalized input so the caller keeps
    its existing "not found / not allowed" error path.
    """
    normalized = normalize_subagent_type(subagent_type)
    resolved = normalized

    find_spec = getattr(parent_agent, "_find_subagent_spec", None)
    if callable(find_spec):
        spec = find_spec(normalized)
        if spec is not None:
            name = subagent_spec_name(spec)
            if name:
                resolved = name

    if allowed_subagent_types is None or resolved in allowed_subagent_types:
        return resolved

    key = canonical_subagent_key(resolved)
    matches = [
        name
        for name in allowed_subagent_types
        if canonical_subagent_key(name) == key
    ]
    if len(matches) == 1:
        return matches[0]
    return resolved