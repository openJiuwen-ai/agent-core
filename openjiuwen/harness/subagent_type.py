"""Deterministic normalization for model-provided subagent type names.

``subagent_type`` is not an enum generated by the harness; it is free-form text
produced by the model in a tool call. Small models frequently emit a
mechanically equivalent spelling instead of the registered name (underscore
instead of hyphen, a Unicode dash, different case, or surrounding whitespace).
This module resolves those variants to an already registered name without
weakening the delegation allow-list.
"""

from __future__ import annotations

import re
from typing import Any, Collection

_UNICODE_DASHES = str.maketrans(
    {
        "\u2010": "-",  # HYPHEN
        "\u2011": "-",  # NON-BREAKING HYPHEN
        "\u2012": "-",  # FIGURE DASH
        "\u2013": "-",  # EN DASH
        "\u2014": "-",  # EM DASH
        "\u2015": "-",  # HORIZONTAL BAR
        "\u2212": "-",  # MINUS SIGN
        "\uff0d": "-",  # FULLWIDTH HYPHEN-MINUS
        "\u00ad": "",   # SOFT HYPHEN (invisible)
        "\u00a0": " ",  # NO-BREAK SPACE
    }
)
_SEPARATORS = re.compile(r"[\s_\-]+")


def normalize_subagent_type(value: object) -> str:
    """Normalize Unicode dash/space variants and surrounding whitespace.

    Separator style is preserved so callers can try an exact match first.
    """
    text = str(value or "")
    if not text:
        return ""
    return text.translate(_UNICODE_DASHES).strip()


def canonical_subagent_key(value: object) -> str:
    """Return a case- and separator-insensitive key for a subagent name."""
    return _SEPARATORS.sub("", normalize_subagent_type(value)).casefold()


def registered_subagent_name(spec: object) -> str:
    """Return the registered name of a ``SubAgentConfig`` or ``DeepAgent``.

    Only real strings are accepted. Tests and host integrations sometimes pass
    a mock parent whose dynamically created attributes are not registered
    names; those must not leak into session ids or tool arguments.
    """
    card = getattr(spec, "agent_card", None) or getattr(spec, "card", None)
    name = getattr(card, "name", None)
    return name if isinstance(name, str) else ""


def resolve_subagent_type_name(
    parent_agent: Any,
    requested_type: object,
    allowed_subagent_types: Collection[str] | None = None,
) -> str:
    """Resolve a model-provided type to a registered, allowed name.

    Resolution order:

    1. Exact / normalized / unique canonical match through the parent agent's
       own subagent registry;
    2. A unique canonical match inside ``allowed_subagent_types`` when the
       parent registry cannot resolve the name (mocks, host adapters).

    When no unique match exists, the normalized input is returned unchanged so
    the caller keeps its existing "not found / not allowed" error path.  This
    function never invents an alias or expands the delegation scope.
    """
    normalized = normalize_subagent_type(requested_type)
    resolved = normalized

    find_spec = getattr(parent_agent, "_find_subagent_spec", None)
    if callable(find_spec):
        spec = find_spec(normalized)
        if spec is not None:
            name = registered_subagent_name(spec)
            if name:
                resolved = name

    if allowed_subagent_types is None or resolved in allowed_subagent_types:
        return resolved

    key = canonical_subagent_key(resolved)
    matches = [
        name
        for name in allowed_subagent_types
        if canonical_subagent_key(name) == key
    ]
    if len(matches) == 1:
        return matches[0]
    return resolved
